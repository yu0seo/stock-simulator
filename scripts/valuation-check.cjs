const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const source=fs.readFileSync('frontend/src/valuation.tsx','utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText;
const exported={};new Function('require','exports',compiled)(require,exported);
const {withValuation,ratioLabel,valuationYear}=exported;
const basis={symbol:'005930',price:20000,per:10,pbr:20,source:'opendart',year:'2025',as_of:'2025-12-31',statement:'연결',eps:2000,bps:1000,per_reason:null,pbr_reason:null,filing_url:null};
