  await load();
  assert.equal(valuationRequests,1,'Long disclosure requests must not overlap');
  assert.equal(rows[0].price,30000);
  resolveValuation({items:[basis]});
  await new Promise(setImmediate);
  assert.equal(rows[0].per,15,'Delayed disclosures must be applied to the latest price');
  assert.equal(rows[0].pbr,30);
