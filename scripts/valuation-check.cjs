assert.equal(withValuation(stock(30000),basis).pbr,30);
assert.equal(withValuation(stock(30000),{...basis,per_reason:'발행주식 수 변경'}).per,null);
assert.equal(withValuation(stock(30000),{...basis,pbr_reason:'유통주식 수 합계 불일치'}).pbr,null);
assert.equal(withValuation(stock(30000),{...basis,eps:0}).per,null);
assert.equal(ratioLabel(withValuation(stock(30000),{...basis,eps:-100,per_reason:'EPS가 0 이하'}),'per'),'적자');
